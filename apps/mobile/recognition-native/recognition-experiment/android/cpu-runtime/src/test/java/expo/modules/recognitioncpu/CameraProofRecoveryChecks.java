package expo.modules.recognitioncpu;

import java.io.*;
import java.nio.file.*;
import java.util.*;
import java.util.concurrent.atomic.AtomicBoolean;

/** Generated state-machine checks. HostIO does NOT prove Android rename/syscall support. */
public final class CameraProofRecoveryChecks {
  private static final String SOURCE="a".repeat(64),PROCESS="11111111-1111-1111-1111-111111111111",NEXT="22222222-2222-2222-2222-222222222222";
  private static int checks;
  private static void check(boolean ok,String message){checks++;if(!ok)throw new AssertionError(message);}
  private interface Work {void run()throws Exception;}
  private static void refuses(File root,Work work)throws Exception{
    Map<String,String> before=inventory(root);
    try{work.run();throw new AssertionError("expected refusal");}catch(IOException|IllegalStateException|IllegalArgumentException expected){checks++;}
    check(before.equals(inventory(root)),"refusal preserves all generated bytes and names");
  }
  private static CameraProofStore open(File root,CameraProofChecks.HostIO io,String process)throws IOException{return new CameraProofStore(root,io,SOURCE,process);}
  private static Map<String,String> inventory(File root)throws Exception{
    Map<String,String> m=new TreeMap<>();for(File f:Objects.requireNonNull(root.listFiles()))m.put(f.getName(),CameraProofFrame.hash(Files.readAllBytes(f.toPath())));return m;
  }
  private static String failedAdmission(File root,CameraProofChecks.HostIO io)throws Exception{
    CameraProofStore s=open(root,io,PROCESS);io.fault="rename";
    CameraProofLifecycle gate=new CameraProofLifecycle();IOException original=null;
    try{gate.begin(s::reserve,new AtomicBoolean());throw new AssertionError("admission must fail");}catch(IOException e){original=e;}
    check(original!=null&&gate.activeId()==null&&!CameraProofLifecycle.SHARED_BUSY.get(),"no SDK owner admitted or fabricated drain");
    check(original.getMessage().equals("injected publish"),"primary pre-ticket publication error survives admission");
    io.fault="";List<String> names=io.list(root);String stage=names.stream().filter(n->n.endsWith(".reservation.new")).findFirst().orElseThrow();
    check(new File(root,stage).length()==148,"complete generated reservation marker, same size as observed residue");
    return stage.substring(0,36);
  }
  private static void publicationFailure(File parent)throws Exception{
    File root=new File(parent,"complete-stage");CameraProofChecks.HostIO io=new CameraProofChecks.HostIO();String ticket=failedAdmission(root,io);
    Map<String,String> before=inventory(root);CameraProofStore restart=open(root,io,NEXT);Map<String,Object> status=restart.status();
    check((Long)status.get("claimedBytes")==CameraProofStore.RESERVATION+(Long)status.get("ownedBytes")-148,"entire claim retained after failure");
    List<Map<String,Object>> inspection=restart.inspectInterrupted();
    check(inspection.size()==1&&inspection.get(0).get("classification").equals("COMPLETE_STAGED_RESERVATION")&&Boolean.TRUE.equals(inspection.get(0).get("reservationValid")),"bounded staged classification");
    check(!inspection.toString().contains(root.getAbsolutePath())&&!inspection.toString().contains(SOURCE),"no paths or reservation content in read-only facts");
    check(before.equals(inventory(root)),"inspection is read-only");
    refuses(root,()->restart.recover(false));
    restart.recover(true);
    Map<String,String> after=inventory(root);check(before.get(ticket+".reservation.new").equals(after.get(ticket+".reservation")),"reservation bytes/hash preserved through exclusive publication");
    check(!after.containsKey(ticket+".receipt.json")&&!after.containsKey(ticket+".numerical.json")&&!after.containsKey(ticket+".raw.jpg"),"no photo/model evidence invented");
    Map<String,String> stable=inventory(root);open(root,io,PROCESS).recover(true);check(stable.equals(inventory(root)),"recovery idempotent across reopen");
    try{restart.readNumerical(ticket);throw new AssertionError("interrupted cannot become successful");}catch(IllegalArgumentException|IllegalStateException e){checks++;}
    check(((Long)restart.status().get("claimedBytes")).longValue()== (Long)restart.status().get("ownedBytes"),"reservation released only after durable interrupted resolution");
    check(((List<?>)restart.status().get("interrupted")).contains(ticket),"interruption stays visible after resolution");
    String next=restart.reserve();check(!next.equals(ticket)&&inventory(root).get(ticket+".reservation").equals(after.get(ticket+".reservation")),"new generated admission possible only after resolution; old evidence retained");
  }
  private static void malformedAndExtra(File parent)throws Exception{
    for(String variant:List.of("truncated","wrong-source","wrong-ticket","wrong-process","wrong-amount","extra-newline","extra-output","partial-request","backup")){
      File root=new File(parent,variant);CameraProofChecks.HostIO io=new CameraProofChecks.HostIO();String ticket=failedAdmission(root,io);
      Path marker=new File(root,ticket+".reservation.new").toPath();String record=Files.readString(marker);
      switch(variant){
        case "truncated":Files.writeString(marker,record.substring(0,70));break;
        case "wrong-source":Files.writeString(marker,record.replace(SOURCE,"b".repeat(64)));break;
        case "wrong-ticket":Files.writeString(marker,record.replace(ticket,NEXT));break;
        case "wrong-process":Files.writeString(marker,record.replace(PROCESS,"-".repeat(36)));break;
        case "wrong-amount":Files.writeString(marker,record.replace(Long.toString(CameraProofStore.RESERVATION),"26009601"));break;
        case "extra-newline":Files.writeString(marker,record+"\n");break;
        case "extra-output":Files.writeString(new File(root,ticket+".raw.jpg").toPath(),"generated output");break;
        case "partial-request":Files.writeString(new File(root,ticket+".request.json.new").toPath(),"{");break;
        case "backup":Files.writeString(new File(root,ticket+".reservation.bak").toPath(),record);break;
        default:throw new AssertionError(variant);
      }
      CameraProofStore reopened=open(root,io,NEXT);Map<String,String> before=inventory(root);
      check(reopened.inspectInterrupted().get(0).get("classification").equals("UNCLASSIFIED_RESIDUE"),"invalid/extra staged record refused:"+variant);
      check(before.equals(inventory(root)),"invalid inspection does not mutate:"+variant);
      refuses(root,()->reopened.recover(true));
      check((Long)reopened.status().get("claimedBytes")>=CameraProofStore.RESERVATION,"invalid residue retains reservation claim");
    }
  }
  private static final class FaultIO extends CameraProofChecks.HostIO {
    String suffix="";boolean after,armed;
    @Override public void publish(File a,File b)throws IOException{
      boolean fail=armed&&b.getName().endsWith(suffix);
      if(fail&&!after){armed=false;throw new IOException("CAMERA_IO_RENAME_EACCES");}
      super.publish(a,b);
      if(fail){armed=false;throw new IOException("CAMERA_IO_DIRECTORY_SYNC_EIO");}
    }
  }
  private static void restartAtEveryPublication(File parent)throws Exception{
    for(String role:List.of("reservation","interruption.json","done","resolution"))for(boolean after:new boolean[]{false,true}){
      File root=new File(parent,"crash-"+role+"-"+after);FaultIO io=new FaultIO();String ticket=failedAdmission(root,io);
      String original=inventory(root).get(ticket+".reservation.new");CameraProofStore restart=open(root,io,NEXT);
      io.suffix="."+role;io.after=after;io.armed=true;
      try{restart.recover(true);throw new AssertionError("fault not reached");}catch(IOException expected){check(expected.getMessage().startsWith("CAMERA_IO_"),"primary publication/sync error retained");}
      check(!inventory(root).containsKey(ticket+".receipt.json"),"interrupted recovery never creates receipt");
      CameraProofStore again=open(root,io,PROCESS);again.recover(true);Map<String,String> stable=inventory(root);
      check(original.equals(stable.get(ticket+".reservation")),"original reservation hash retained:"+role);
      check(stable.containsKey(ticket+".resolution")&&!stable.containsKey(ticket+".resolution.new"),"terminal interruption after reopen:"+role);
      check(Files.readString(new File(root,ticket+".resolution").toPath()).contains("\nINTERRUPTED\n"),"never published success");
      open(root,io,NEXT).recover(true);check(stable.equals(inventory(root)),"restart recovery is idempotent:"+role+after);
      check(((Long)again.status().get("claimedBytes")).longValue()==(Long)again.status().get("ownedBytes"),"all retained bytes charged after classification");
    }
  }
  private static void corruptRecoveryStages(File parent)throws Exception{
    for(String role:List.of("interruption.json","done","resolution")){
      File root=new File(parent,"corrupt-"+role);FaultIO io=new FaultIO();String ticket=failedAdmission(root,io);
      io.suffix="."+role;io.armed=true;try{open(root,io,NEXT).recover(true);throw new AssertionError("fault not reached");}catch(IOException expected){checks++;}
      Path staged=new File(root,ticket+"."+role+".new").toPath();Files.writeString(staged,"generated partial/corrupt marker");
      CameraProofStore restart=open(root,io,PROCESS);refuses(root,()->restart.recover(true));
      check((Long)restart.status().get("claimedBytes")>=CameraProofStore.RESERVATION,"corrupt recovery draft never releases claim");
    }
  }
  private static void destinationAndSubstitution(File parent)throws Exception{
    File root=new File(parent,"collision");CameraProofChecks.HostIO io=new CameraProofChecks.HostIO();String ticket=failedAdmission(root,io);
    File stage=new File(root,ticket+".reservation.new"),destination=new File(root,ticket+".reservation");
    Files.writeString(destination.toPath(),"generated destination sentinel");refuses(root,()->io.publish(stage,destination));
    check(Files.readString(destination.toPath()).equals("generated destination sentinel"),"existing destination is never overwritten by host boundary");
    File other=new File(parent,"substitution");CameraProofChecks.HostIO changed=new CameraProofChecks.HostIO(){
      @Override public void publish(File a,File b)throws IOException{super.publish(a,b);if(b.getName().endsWith(".reservation"))Files.writeString(b.toPath(),"generated substitution");}
    };
    String id=failedAdmission(other,changed);CameraProofStore reopen=open(other,changed,NEXT);
    try{reopen.recover(true);throw new AssertionError("changed reservation accepted");}catch(IllegalArgumentException expected){check(expected.getMessage().equals("CAMERA_RESERVATION_PUBLICATION_CHANGED"),"post-publication substitution refuses before interruption append");}
    check(!new File(other,id+".interruption.json").exists(),"no classification after substitution");
  }
  private static void ambiguousMetadata(File parent)throws Exception{
    for(String role:List.of("done.new","resolution.new","interruption.json.bak")){
      File root=new File(parent,"ambiguous-"+role);CameraProofChecks.HostIO io=new CameraProofChecks.HostIO();String ticket=failedAdmission(root,io);
      io.publish(new File(root,ticket+".reservation.new"),new File(root,ticket+".reservation"));
      Files.writeString(new File(root,ticket+"."+role).toPath(),"generated ambiguous metadata");
      CameraProofStore reopened=open(root,io,NEXT);refuses(root,()->reopened.recover(true));
    }
  }
  public static void main(String[] args)throws Exception{
    File parent=new File(args[0]);if(!parent.mkdir())throw new IOException("exclusive generated destination");publicationFailure(parent);malformedAndExtra(parent);restartAtEveryPublication(parent);corruptRecoveryStages(parent);destinationAndSubstitution(parent);ambiguousMetadata(parent);
    System.out.println("{\"kind\":\"GENERATED_CAMERA_RECOVERY_CHECKS\",\"checks\":"+checks+",\"nativeValidated\":false,\"modelExecuted\":false}");
  }
}
