import { act, render, screen } from '@testing-library/react-native';
import { AccessibilityInfo, Animated, DeviceEventEmitter } from 'react-native';
import ScannerActivity from '../src/features/scanning/ScannerActivity';
const hidden = { includeHiddenElements: true };
it('starts restrained activity only with motion allowed and stops on pause/unmount', async () => {
  const motion = jest.spyOn(AccessibilityInfo, 'isReduceMotionEnabled').mockResolvedValue(false);
  const start = jest.fn();
  const stop = jest.fn();
  const loop = jest.spyOn(Animated, 'loop').mockReturnValue({ start, stop, reset: jest.fn() });
  const view = render(<ScannerActivity active />);
  await act(async () => {});
  expect(start).toHaveBeenCalledTimes(1);
  expect(screen.getByTestId('scanner-frame', hidden).props.pointerEvents).toBe('none');
  expect(screen.getByTestId('scanner-frame', hidden).props.importantForAccessibility).toBe('no-hide-descendants');
  for (const corner of ['tl','tr','bl','br']) expect(screen.getByTestId(`scanner-corner-${corner}`, hidden)).toBeTruthy();
  expect(screen.getByTestId('scanner-sweep', hidden)).toBeTruthy();
  view.rerender(<ScannerActivity active={false} />);
  expect(stop).toHaveBeenCalledTimes(1);
  expect(screen.queryByTestId('scanner-frame', hidden)).toBeNull();
  view.unmount();
  loop.mockRestore(); motion.mockRestore();
});
it('reduced motion keeps static framing and stops a running line when preference changes', async () => {
  let change!: (value: boolean) => void;
  const motion = jest.spyOn(AccessibilityInfo, 'isReduceMotionEnabled').mockResolvedValue(true);
  const subscription = jest.spyOn(AccessibilityInfo, 'addEventListener').mockImplementation((_event: string, callback: unknown) => { change = callback as (value: boolean) => void; return DeviceEventEmitter.addListener('test-reduced-motion', () => undefined); });
  const stop = jest.fn();
  const loop = jest.spyOn(Animated, 'loop').mockReturnValue({ start: jest.fn(), stop, reset: jest.fn() });
  const view = render(<ScannerActivity active />);
  await act(async () => {});
  expect(screen.getByTestId('scanner-frame', hidden)).toBeTruthy();
  expect(screen.queryByTestId('scanner-sweep', hidden)).toBeNull();
  expect(loop).not.toHaveBeenCalled();
  act(() => change(false));
  expect(screen.getByTestId('scanner-sweep', hidden)).toBeTruthy();
  act(() => change(true));
  expect(stop).toHaveBeenCalledTimes(1);
  expect(screen.queryByTestId('scanner-sweep', hidden)).toBeNull();
  view.unmount(); loop.mockRestore(); subscription.mockRestore(); motion.mockRestore();
});
